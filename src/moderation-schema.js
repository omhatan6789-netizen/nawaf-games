import { pool } from "./db.js";

let ready = null;

export async function ensureModerationSchema() {
  if (!pool) throw new Error("DATABASE_URL is not configured");
  if (ready) return ready;
  ready = (async () => {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS moderation_settings (
        chat_id BIGINT PRIMARY KEY,
        durations_enabled BOOLEAN NOT NULL DEFAULT FALSE,
        reasons_enabled BOOLEAN NOT NULL DEFAULT FALSE
      );
      CREATE TABLE IF NOT EXISTS bot_mutes (
        chat_id BIGINT NOT NULL, user_id BIGINT NOT NULL, username TEXT, first_name TEXT,
        until_time TIMESTAMPTZ, reason TEXT, by_user BIGINT, PRIMARY KEY(chat_id,user_id)
      );
      CREATE TABLE IF NOT EXISTS restrictions (
        chat_id BIGINT NOT NULL, user_id BIGINT NOT NULL, username TEXT, first_name TEXT,
        until_time TIMESTAMPTZ, reason TEXT, by_user BIGINT, PRIMARY KEY(chat_id,user_id)
      );
      CREATE TABLE IF NOT EXISTS moderation_bans (
        chat_id BIGINT NOT NULL, user_id BIGINT NOT NULL, username TEXT, first_name TEXT,
        until_time TIMESTAMPTZ, reason TEXT, by_user BIGINT, PRIMARY KEY(chat_id,user_id)
      );
      CREATE TABLE IF NOT EXISTS warnings (
        chat_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
        warning_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source TEXT NOT NULL DEFAULT 'manual', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS protection_settings (
        chat_id BIGINT PRIMARY KEY,
        repetition_enabled BOOLEAN NOT NULL DEFAULT FALSE,
        repetition_limit INTEGER NOT NULL DEFAULT 3,
        repetition_seconds INTEGER NOT NULL DEFAULT 5,
        repetition_action TEXT NOT NULL DEFAULT 'mute',
        repetition_punishment_duration INTEGER NOT NULL DEFAULT 300,
        repetition_rank TEXT NOT NULL DEFAULT 'عضو'
      );
      CREATE TABLE IF NOT EXISTS blocked_words_v2 (
        chat_id BIGINT NOT NULL, list_id INTEGER NOT NULL CHECK(list_id IN (1,2)),
        word TEXT NOT NULL, PRIMARY KEY(chat_id,list_id,word)
      );
      CREATE TABLE IF NOT EXISTS blocked_words_settings_v2 (
        chat_id BIGINT NOT NULL, list_id INTEGER NOT NULL CHECK(list_id IN (1,2)),
        enabled BOOLEAN NOT NULL DEFAULT FALSE, action TEXT NOT NULL DEFAULT 'mute',
        duration INTEGER, warning_duration INTEGER, warning_action TEXT,
        warning_punishment_duration INTEGER, PRIMARY KEY(chat_id,list_id)
      );
      CREATE TABLE IF NOT EXISTS blocked_words_warnings_v2 (
        chat_id BIGINT NOT NULL, list_id INTEGER NOT NULL, user_id BIGINT NOT NULL,
        warning_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        expires_at BIGINT NOT NULL, created_at BIGINT NOT NULL
      );
      CREATE INDEX IF NOT EXISTS idx_bot_mutes_expiry ON bot_mutes(until_time);
      CREATE INDEX IF NOT EXISTS idx_restrictions_expiry ON restrictions(until_time);
      CREATE INDEX IF NOT EXISTS idx_moderation_bans_expiry ON moderation_bans(until_time);
      CREATE INDEX IF NOT EXISTS idx_blocked_words_expiry ON blocked_words_warnings_v2(expires_at);
    `);
    console.log("Moderation database schema is ready.");
  })().catch(error => { ready = null; throw error; });
  return ready;
}
